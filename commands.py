# git clone [https link of repository] --> This command is used to clone a repository files from github to a local editor.
# {clear} command is used to clear the terminal screen.
# {git status} command is used to check the status of the repository.
# {git add .} command is used to add all the files to the staging area.
# {git commit -m "message"} command is used to commit the changes to the local repository with a message.
# {git push origin master} this command is used to push the changes to the remote repo.
